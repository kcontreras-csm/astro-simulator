#!/usr/bin/env node
/* Render the UI icons from react-icons (Lucide set, react-icons/lu) to static SVG strings.
   The app is plain HTML/JS with no build step, so react-icons is only used here, at build time.

   Setup (once, outside the repo):  mkdir -p /tmp/ri && cd /tmp/ri && npm i react-icons react react-dom
   Run:                             NODE_PATH=/tmp/ri/node_modules node tools/build_icons.mjs
   Writes assets/icons.js — commit that file; node_modules is never needed at runtime.

   To add an icon: add a line to ICONS below (name → react-icons/lu export) and rerun. */
import { createRequire } from "module";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const require = createRequire(import.meta.url);
const React = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const lu = require("react-icons/lu");

const ICONS = {
  "zap": "LuZap", "eye": "LuEye", "eye-off": "LuEyeOff", "reset": "LuRotateCcw", "palette": "LuPalette",
  "moon": "LuMoon", "sun": "LuSun", "flag": "LuFlag", "timer": "LuTimer", "target": "LuTarget",
  "chart": "LuChartColumn", "progress": "LuListChecks", "dashboard": "LuLayoutDashboard", "shuffle": "LuShuffle",
  "trash": "LuTrash2", "alert": "LuTriangleAlert", "bulb": "LuLightbulb", "key": "LuKeyRound", "check": "LuCheck",
  "x": "LuX", "arrow-right": "LuArrowRight", "flame": "LuFlame", "infinity": "LuInfinity", "trophy": "LuTrophy",
  "undo": "LuUndo2", "save": "LuSave", "book": "LuBookOpen", "folders": "LuFolderTree", "clipboard": "LuClipboardList",
  "party": "LuPartyPopper", "sparkles": "LuSparkles", "star": "LuStar", "cloud": "LuCloud", "heart": "LuHeart",
  "grad": "LuGraduationCap", "footprints": "LuFootprints", "rocket": "LuRocket", "circle-check": "LuCircleCheck",
  "circle-x": "LuCircleX", "notebook": "LuNotebookPen", "gauge": "LuGauge", "layers": "LuLayers",
  "github": "LuGithub", "home": "LuHouse", "more": "LuEllipsis",
};

const out = {};
for (const [name, comp] of Object.entries(ICONS)) {
  if (!lu[comp]) throw new Error(`react-icons/lu has no ${comp}`);
  out[name] = renderToStaticMarkup(React.createElement(lu[comp], { size: "1em", "aria-hidden": "true", focusable: "false" }))
    .replace(/ style="[^"]*"/, "")
    .replace("<svg ", '<svg class="ico" ');
}

const pkgDir = path.dirname(path.dirname(require.resolve("react-icons/lu")));
const version = JSON.parse(fs.readFileSync(path.join(pkgDir, "package.json"), "utf8")).version;
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const js = `// Generated by tools/build_icons.mjs from react-icons ${version} (Lucide) — do not edit by hand.
"use strict";
const ICONS = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n  "').replace(/^\{/, "{\n  ").replace(/\}$/, "\n}")};

// icon("zap") → inline SVG string (decorative, aria-hidden). Unknown names render nothing.
function icon(name, cls) {
  const svg = ICONS[name] || "";
  return cls ? svg.replace('class="ico"', \`class="ico \${cls}"\`) : svg;
}

// Static markup uses <i data-icon="name"></i> placeholders; fill them in.
function hydrateIcons(root) {
  (root || document).querySelectorAll("[data-icon]").forEach(el => {
    if (!el.firstElementChild) el.innerHTML = icon(el.dataset.icon);
  });
}
hydrateIcons();
`;
fs.writeFileSync(path.join(ROOT, "assets/icons.js"), js);
console.log(`${Object.keys(out).length} icons → assets/icons.js (${js.length} bytes)`);
